-- 2. Write a Select statement to display the FirstName, LastName, and EmailAddress of all desk holders whose ReferralSourceCode is 2.
SELECT
	FIRSTNAME,
	LASTNAME,
	EMAILADDRESS
FROM
	DESKHOLDER
WHERE
	REFERRALSOURCECODE = 2;

-- 3. Write a Select statement that displays the DeskHolderID and a concatenated full name column called "Desk Holder Name" from the DeskHolder table.
SELECT
	DESKHOLDERID,
	FIRSTNAME || ' ' || LASTNAME AS "Desk Holder Name"
FROM
	DESKHOLDER;

-- 4. Write a Select statement that displays the OfficeNumber, MonthlyRent, and WindowQuantity for offices where the MonthlyRent is greater than 1200 and the WindowQuantity is at least 2.
SELECT
	OFFICENUMBER,
	MONTHLYRENT,
	WINDOWQUANTITY
FROM
	OFFICE
WHERE
	MONTHLYRENT > 1200
	AND WINDOWQUANTITY >= 2;

-- 5. Write a select statement that displays all office add-ons whose AddonDescription begins with the letter 'C' using the LIKE operator.
SELECT
	ADDONNUMBER,
	ADDONDESCRIPTION,
	CURRENTCOST,
	CURRENTPRICE
FROM
	OFFICEADDON
WHERE
	ADDONDESCRIPTION LIKE 'C%';

-- 6. Write a Select statement that displays the FirstName and LastName of desk holders whose last name contains the letters “son” anywhere in the value using the LIKE operator.
SELECT
	FIRSTNAME,
	LASTNAME
FROM
	DESKHOLDER
WHERE
	LASTNAME LIKE '%son%';

-- 7. Write a Select statement that displays the DeskHolderID, FirstName, and LastName of desk holders whose DeskHolderID starts with exactly three uppercase letters followed by three numbers using a PostgreSQL regular expression.
SELECT
	DESKHOLDERID,
	FIRSTNAME,
	LASTNAME
FROM
	DESKHOLDER
WHERE
	DESKHOLDERID ~ '^[A-Z]{3}[0-9]{3}$';


-- 8, Write a Select statement that displays the InvoiceNumber, InvoiceDate, and InvoiceTotal from the Invoice table sorted by InvoiceTotal in descending order.

SELECT INVOICENUMBER, INVOICEDATE, INVOICETOTAL
FROM INVOICE
ORDER BY INVOICETOTAL DESC;

-- 9. Write a Select statement that displays a unique list of ReferralSourceCode values from the DeskHolder table sorted in ascending order.

SELECT REFERRALSOURCECODE
FROM DESKHOLDER
ORDER BY REFERRALSOURCECODE ASC;

-- 10. Write a Select statement that displays the LeaseNumber, OfficeNumber, and TotalLeasePrice for leases where the TotalLeasePrice is between 500 and 20000, sorted from highest lease price to lowest lease price.

