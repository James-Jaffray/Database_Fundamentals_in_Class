	LEASETYPENUMBER DECIMAL(2, 0) CONSTRAINT NN_LEASE_LEASETYPENUMBER NOT NULL CONSTRAINT FK_LEASE_LEASETYPENUMBER_LEASETYPE_LEASETYPENUMBER REFERENCES LEASETYPE (LEASETYPENUMBER)
