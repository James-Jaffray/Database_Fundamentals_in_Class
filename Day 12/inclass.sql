CREATE TABLE LEASE -- LSE
(
	LEASENUMBER DECIMAL(6, 0) CONSTRAINT PK_LEASE_LEASENUMBER PRIMARY KEY CONSTRAINT NN_LEASE_LEASENUMBER NOT NULL,
	STARTDATE TIMESTAMP CONSTRAINT NN_LEASE_STARTDATE NOT NULL CONSTRAINT CK_LEASE_STARTDATE_GREQ01JAN2020 CHECK (
		STARTDATE >= TO_TIMESTAMP('01-JAN-2020', 'DD-MON-YYYY')
