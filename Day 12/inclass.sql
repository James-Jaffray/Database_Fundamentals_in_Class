CREATE TABLE OFFICE (
	OFFICENUMBER DECIMAL(3, 0) CONSTRAINT PK_OFFICE_OFFICENUMBER PRIMARY KEY CONSTRAINT NN_OFFICE_OFFICENUMBER NOT NULL,
	MONTHLYRENT DECIMAL(6, 2) CONSTRAINT NN_OFFICE_MONTHLYRENT NOT NULL CONSTRAINT CK_OFFICE_MONTHLYRENT_GREQZERO CHECK (MONTHLYRENT >= 0) CONSTRAINT DF_OFFICE_MONTHLYRENT_ZERO DEFAULT 0,
	SQUAREFOOTAGE DECIMAL(6, 2) CONSTRAINT NN_OFFICE_SQUAREFOOTAGE NOT NULL,
	BOOKSHELFYN CHAR(1) CONSTRAINT NN_OFFICE_BOOKSHELFYN NOT NULL CONSTRAINT CK_OFFICE_BOOKSHELFYN_YN CHECK (BOOKSHELFYN IN ('Y', 'N')) CONSTRAINT DF_OFFICE_BOOKSHELFYN_N DEFAULT ('N'),
	EXTRAFILINGCABINETYN CHAR(1) CONSTRAINT NN_OFFICE_EXTRAFILINGCABINETYN NOT NULL,
	MEETINGTABLEYN CHAR(1) CONSTRAINT NN_OFFICE_MEETINGTABLEYN NOT NULL,
	WINDOWQUANTITY DECIMAL(2, 0) CONSTRAINT NN_OFFICE_WINDOWQUANTITY NOT NULL CONSTRAINT CK_OFFICE_WINDOWQUANTITY_GRZERO CHECK (WINDOWQUANTITY > 0) CONSTRAINT DF_OFFICE_WINDOWQUANTITY_ONE DEFAULT 1,
	WINDOWSTATUS CHAR(1) CONSTRAINT NN_OFFICE_WINDOWSTATUS NOT NULL CONSTRAINT CK_OFFICE_WINDOWSTATUS CHECK (WINDOWSTATUS IN ('O', 'F')),
	OFFICETYPECODE DECIMAL(2, 0) CONSTRAINT NN_OFFICE_OFFICETYPECODE NOT NULL CONSTRAINT FK_OFFICE_OFFICETYPECODE_OFFICETYPE_OFFICETYPECODE REFERENCES OFFICETYPE (OFFICETYPECODE)
);

SELECT
	*
FROM
	OFFICE;

